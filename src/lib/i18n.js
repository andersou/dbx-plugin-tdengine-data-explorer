export function translate(locale, key, vars = {}) {
  const language = String(locale ?? "").split("-")[0];
  const code = Object.hasOwn(MESSAGES, String(locale)) ? locale : Object.keys(MESSAGES).find((candidate) => candidate.split("-")[0] === language);
  const text = MESSAGES[code ?? "en"][key] ?? MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}
